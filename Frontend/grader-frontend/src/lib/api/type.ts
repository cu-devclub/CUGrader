export interface InstructorsAndTAs {
  instructors: Instructor[],
  teachingAssistant: TeachingAssistant[];
}

export interface ParticipatingClasses {
  studying: Class[];
  assisting: Class[];
}

export interface CreateStudentPayload {
  email: string,
  section: number,
  group?: string;
}

export interface UpdateStudentPayload {
  section?: number,
  group?: string,
  withdrawed?: boolean;
}

export interface CreateClassPayload {
  courseId: string;
  name: string;
  semester: Semester;
  image?: File;
  /**
   * Student csv file
   */
  students?: File;
}

export type UpdateClassPayload = Partial<CreateClassPayload>;

export type CreateLabPayload = Omit<Assignment, "id" | "languages" | "questionIds" | "maxScore"> & {
  closeOnDue: boolean;
  showScoreOnLock: boolean; // hideOnClose ??? -> which mean we have some kind of state `isLocked` from the api

  template: string; // code that you give to the student

  languages: SupportedLanguage[]; // select at least one

  assignedGroupIds: string[];

  testCode: string; // code, like in 2024 class
  secretTestCode: string;

  questions: Question[];
  additionalFiles: File[];
};

export type UpdateLabPayload = Omit<CreateLabPayload, "additionalFiles"> & {
  // WE CANT REMOVE FILE USING THIS REQ
  filesToAdd: File[];
  examMode: boolean;
  examPin: string; // 6 digit num
};

