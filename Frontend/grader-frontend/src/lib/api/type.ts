import { CalendarDateTime } from "@internationalized/date";

export type Semester = `${number}/${string}`;

export interface Class {
  classId: number, // map to class_id
  courseId: string;
  courseName: string;
  imageUrl?: string;
}

export interface TeachingClass extends Class {
  sections: number[]; // should be string, not exist
}

export interface Student {
  studentId: string;
  name: string;
  // email: string;
  section: number;
  group: string;
  imageUrl?: string;
  withdrawed: boolean;
  // TODO: think about this
  score: number;
  maxScore: number;
}

export interface Instructor {
  name: string;
  imageUrl?: string;
  email: string; // TODO: tell backend to add this
}

export interface ClassParticipants {
  instructors: Instructor[],
  teachingAssistants: TeachingAssistant[],
  students: Student[],
}

export interface TeachingAssistant {
  name: string;
  email: string;  // TODO: tell backend to add this
  imageUrl?: string;
  leader: boolean;
}

export interface LabNotification {
  courseId: number;
  courseName: string;
  id: number;
  name: string;
  due: Date;
  maxScore: number;
}

export interface Testcase {
  input: string;
  output: string;
}

